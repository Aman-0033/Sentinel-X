"""ML detection classification record."""

from datetime import datetime, timezone
from decimal import Decimal
from typing import TYPE_CHECKING, Any, Dict, List, Optional

from sqlalchemy import Boolean, CheckConstraint, DateTime, ForeignKey, Index, Numeric, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import JSONB_TYPE, Base, UUIDPrimaryKeyMixin

if TYPE_CHECKING:
    from app.db.models.analyst_feedback import AnalystFeedback
    from app.db.models.incident import Incident
    from app.db.models.incident_detection import IncidentDetection
    from app.db.models.model_version import ModelVersion
    from app.db.models.network_flow import NetworkFlow
    from app.db.models.threat_intel import ThreatIntelEnrichment


class Detection(Base, UUIDPrimaryKeyMixin):
    """Detection event generated by inference pipeline."""

    __tablename__ = "detections"
    __table_args__ = (
        CheckConstraint(
            "confidence >= 0 AND confidence <= 1",
            name="ck_detections_confidence",
        ),
        CheckConstraint(
            "risk_score >= 0 AND risk_score <= 100",
            name="ck_detections_risk_score",
        ),
        CheckConstraint(
            "severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')",
            name="ck_detections_severity",
        ),
        Index("ix_detections_detected_at", "detected_at"),
        Index("ix_detections_severity", "severity"),
        Index("ix_detections_attack_type", "attack_type"),
        Index("ix_detections_risk_score", "risk_score"),
    )

    flow_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("network_flows.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    model_version_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("model_versions.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    attack_type: Mapped[str] = mapped_column(String(100), nullable=False)
    confidence: Mapped[Decimal] = mapped_column(Numeric(5, 4), nullable=False)
    anomaly_score: Mapped[Optional[Decimal]] = mapped_column(Numeric(8, 5), nullable=True)
    risk_score: Mapped[Decimal] = mapped_column(Numeric(5, 2), nullable=False)
    severity: Mapped[str] = mapped_column(String(20), nullable=False)
    is_anomaly: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    explanation: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSONB_TYPE, nullable=True)
    detected_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    flow: Mapped["NetworkFlow"] = relationship("NetworkFlow", back_populates="detections")
    model_version: Mapped["ModelVersion"] = relationship(
        "ModelVersion", back_populates="detections"
    )
    threat_intel_enrichments: Mapped[List["ThreatIntelEnrichment"]] = relationship(
        "ThreatIntelEnrichment",
        back_populates="detection",
        cascade="all, delete-orphan",
    )
    incident_associations: Mapped[List["IncidentDetection"]] = relationship(
        "IncidentDetection",
        back_populates="detection",
        cascade="all, delete-orphan",
    )
    incidents: Mapped[List["Incident"]] = relationship(
        "Incident",
        secondary="incident_detections",
        back_populates="detections",
        viewonly=True,
    )
    analyst_feedback: Mapped[List["AnalystFeedback"]] = relationship(
        "AnalystFeedback",
        back_populates="detection",
        cascade="all, delete-orphan",
    )
